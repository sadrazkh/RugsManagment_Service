import { describe, expect, it } from 'vitest'
import { moneyWords, toWords } from './numWords'

describe('عدد به حروف — همان قاعده‌های NumberWords.cs', () => {
  it.each([
    [0, 'صفر'],
    [1, 'یک'],
    [11, 'یازده'],
    [19, 'نوزده'],
    [20, 'بیست'],
    [25, 'بیست و پنج'],
    [100, 'صد'],
    [125, 'صد و بیست و پنج'],
    [999, 'نهصد و نود و نه'],
    [1000, 'هزار'],
    [1001, 'هزار و یک'],
    [2000, 'دو هزار'],
    [21000, 'بیست و یک هزار'],
    [85000, 'هشتاد و پنج هزار'],
    [1_000_000, 'یک میلیون'],
    [1_250_000, 'یک میلیون و دویست و پنجاه هزار'],
    [10_000_000, 'ده میلیون'],
    [1_440_000, 'یک میلیون و چهارصد و چهل هزار'],
    [38_272_700, 'سی و هشت میلیون و دویست و هفتاد و دو هزار و هفتصد'],
    [1_000_000_000, 'یک میلیارد'],
    [1_001_000, 'یک میلیون و هزار'],
  ])('%d → «%s»', (value, words) => {
    expect(toWords(value)).toBe(words)
  })

  it('اعشار تا سه رقم، صفرهای انتهایی حذف', () => {
    expect(toWords('2.5')).toBe('دو و پنج دهم')
    expect(toWords('2.50')).toBe('دو و پنج دهم')
    expect(toWords('0.25')).toBe('بیست و پنج صدم')
    expect(toWords('3.125')).toBe('سه و صد و بیست و پنج هزارم')
    expect(toWords('0.001')).toBe('یک هزارم')
    expect(toWords('7.29')).toBe('هفت و بیست و نه صدم')
  })

  it('بیش از سه رقم اعشار دور از صفر گرد می‌شود', () => {
    expect(toWords('0.0005')).toBe('یک هزارم')
    expect(toWords('0.0004')).toBe('صفر')
    expect(toWords('1.9995')).toBe('دو')
  })

  it('منفی', () => {
    expect(toWords(-500)).toBe('منفی پانصد')
    expect(toWords('-2.5')).toBe('منفی دو و پنج دهم')
  })

  it('مبلغ‌های بزرگ دقیق (فراتر از ۲^۵۳)', () => {
    expect(toWords('999999999999999999')).toBe(
      'نهصد و نود و نه کوادریلیون و نهصد و نود و نه تریلیون و نهصد و نود و نه میلیارد و نهصد و نود و نه میلیون و نهصد و نود و نه هزار و نهصد و نود و نه',
    )
  })

  it('بزرگ‌تر از ۹۹۹ کوادریلیون: با ارقام فارسی', () => {
    expect(toWords('1000000000000000000')).toBe('۱٬۰۰۰٬۰۰۰٬۰۰۰٬۰۰۰٬۰۰۰٬۰۰۰')
  })

  it('ورودی خالی یا نامعتبر', () => {
    expect(toWords(null)).toBe('')
    expect(toWords('abc')).toBe('')
  })
})

describe('مبلغ به حروف', () => {
  it('«ده میلیون تومان»', () => {
    expect(moneyWords(10_000_000, 'تومان')).toBe('ده میلیون تومان')
    expect(moneyWords(1_000_000, 'ریال')).toBe('یک میلیون ریال')
    expect(moneyWords(500, '')).toBe('پانصد')
    expect(moneyWords(null, 'تومان')).toBe('')
  })
})
