namespace RugsManagment.Domain.Enums;

/// <summary>
/// نقش کاربر در سیستم — تعیین می‌کند چه منو و APIهایی در دسترس است.
///
/// فقط افزودنی با مقدار صریح: عدد نقش در دیتابیس و داخل کوکی‌های فعلی نشسته، پس جابه‌جا کردن
/// یک مقدار نقش کاربرانِ موجود را بی‌صدا عوض می‌کرد. برچسب فارسی هر نقش فقط در <c>RoleLabels</c> است.
/// </summary>
public enum UserRole
{
    /// <summary>مدیر کل سامانه؛ کارگاه می‌سازد، به Tenant وابسته نیست</summary>
    SystemAdmin = 0,

    /// <summary>
    /// «تنظیم‌کننده (مدیر)»: یک بار کارگاه را می‌چیند (کاربران، فیلدها، قالب‌ها، ترجیحات) و همهٔ
    /// کارهای بازرگان را هم می‌تواند بکند. سیاست‌های Floor، Business و Configure.
    /// </summary>
    TenantAdmin = 1,

    /// <summary>
    /// «کاربر / انباردار»: ثبت فرش، نگله‌بندی و اندازهٔ نهایی؛ هیچ مبلغ تومانی نمی‌بیند (فقط Floor).
    /// </summary>
    Operator = 2,

    /// <summary>
    /// «بازرگان»: کاربر روزانهٔ کارگاه صادراتی. همهٔ پول‌ها، محموله‌ها، هزینه‌ها و خروجی‌ها را دارد
    /// (Floor و Business) ولی تنظیمات کارگاه را نه — آن کار تنظیم‌کننده است.
    /// </summary>
    Merchant = 3
}
