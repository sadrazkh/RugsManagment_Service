namespace RugsManagment.Domain.Enums;

/// <summary>
/// مبنای یک مبلغ: کل، هر متر، هر تخته یا درصد.
///
/// قاعدهٔ دسته (spec D.3) برای هر مبنا جداست: «هر متر» و «هر تخته» اول برای یک تخته گرد و بعد در تعداد
/// ضرب می‌شوند، «کل» یک بار گرد می‌شود، «درصد» یک بار روی جمع سطرهای غیردرصدیِ همان فرش.
/// <see cref="Percent"/> فقط برای سطرهای خرید فرش است (دلالی)، نه برای ثبت هزینه. فقط افزودنی با عدد صریح.
/// </summary>
public enum CostBasis
{
    /// <summary>مبلغ کل</summary>
    Total = 0,

    /// <summary>نرخ برای هر متر مربع (سطر خرید همیشه روی اندازهٔ اول)</summary>
    PerM2 = 1,

    /// <summary>نرخ برای هر تخته</summary>
    PerPiece = 2,

    /// <summary>درصد از جمع سطرهای غیردرصدی خرید همان فرش (فقط سطر خرید)</summary>
    Percent = 3
}
