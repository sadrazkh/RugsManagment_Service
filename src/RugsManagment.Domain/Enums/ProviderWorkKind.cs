namespace RugsManagment.Domain.Enums;

/// <summary>
/// نوع یک ردیف در صورت‌حساب طرف خدمات (spec B.14، I.3 <c>ProviderWorkItemDto.Kind</c>).
///
/// چرا جدا: تا فاز هزینه‌ها هر ردیف صورت‌حساب یک «مرحلهٔ کارگاه» روی یک فرش بود. از فاز هزینه‌ها رسید یک کارگاه
/// (مثلاً شستشوی ۵۲ تخته با یک رسید) یک ثبت هزینه است که چند فرش را می‌پوشاند؛ صورت‌حساب آن را یک ردیف «رسید» نشان
/// می‌دهد با شمارهٔ ثبت و تعداد فرش، نه ۵۲ ردیف جدا. فقط افزودنی با عدد صریح.
/// </summary>
public enum ProviderWorkKind
{
    /// <summary>یک مرحلهٔ کارگاه روی یک فرش (مسیر قدیمی).</summary>
    Step = 0,

    /// <summary>یک رسید (ثبت هزینه با این طرف خدمات) که چند فرش را می‌پوشاند.</summary>
    Receipt = 1
}
