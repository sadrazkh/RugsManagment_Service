namespace RugsManagment.Domain.Enums;

/// <summary>
/// ارزش گمرکی (دلار هر متر) یک خط از کجا آمده (spec C.5)، به ترتیب اولویت: نرخ دستیِ همان خط، جدول ارزش گمرکی با
/// مقدار فیلد کلید (پیش‌فرض «محل بافت»)، نرخ پیش‌فرض کارگاه، و در آخر «ندارد» — که جلوی قطعی شدن را می‌گیرد.
/// چیپ نرخ در جدول نگله‌ها همین را نشان می‌دهد («دستی» / «از جدول» / «نرخ پیش‌فرض» / «ندارد»). فقط افزودنی با عدد صریح.
/// </summary>
public enum DeclaredRateSource
{
    /// <summary>«دستی»: بازرگان برای همین خط نرخ نوشته.</summary>
