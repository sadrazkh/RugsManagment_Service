namespace RugsManagment.Domain.Enums;

/// <summary>
/// وضع تقسیم یک ثبت هزینه بعد از آخرین اجرای پاس سازگاری (spec D.3، B.10 <c>CostEntryResult.State</c>).
///
/// چرا سه حالت و نه «تقسیم شد / نشد»: ثبتی که همهٔ فرش‌هایش مبلغ ثابت دارند ولی جمعشان با کل نمی‌خواند، یا روش «دستی»
/// که سهم‌ها کمتر از کل است، بخشی از پول را بی‌صاحب می‌گذارد؛ این «تقسیم‌شدهٔ ناقص» است و باید در فهرست با تراشهٔ
/// «… تومان هنوز تقسیم نشده» دیده شود، نه اینکه مثل «تقسیم‌نشده» (هیچ فرشی ندارد) یا «تقسیم‌شده» نشان داده شود.
/// فقط افزودنی با عدد صریح.
/// </summary>
public enum AllocationState
{
    /// <summary>همهٔ مبلغ بین فرش‌ها تقسیم شد (Allocated = BaseAmount).</summary>
    Allocated = 0,

    /// <summary>بخشی تقسیم شد و باقی‌مانده بی‌صاحب ماند (مبلغ‌های ثابت یا روش «دستی»).</summary>
    Partial = 1,

    /// <summary>هیچ فرشی برای تقسیم نیست؛ کل مبلغ «تقسیم‌نشده» است.</summary>
    Unallocated = 2
}
